#!/usr/bin/env python3
"""Builds every form of the Combine "claw" emblem from one description of its shape.

The shape is measured off the game's own propaganda poster (props/paperposter003a, the
black claw on green): a disc, a clear ring around it, and a claw that wraps the ring from
below and the right, with two prongs running to points at the upper left.

    make-emblem.py            write all outputs
    make-emblem.py --check    also compare against the poster texture and save an overlay

Outputs:
    assets/claw.svg                         white vector, tinted by core/Emblem.qml
    boot/plymouth/overwatch/logo.png        boot splash: claw, OVERWATCH, Combine-script line
    ~/.config/fastfetch/emblem.txt          the same claw in half-block characters
Run through the private venv (needs PIL): ~/.local/share/overwatch/venv/bin/python make-emblem.py
"""
import math, os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.realpath(__file__))
ROOT = os.path.dirname(HERE)
HOME = os.path.expanduser("~")
DATA = HOME + "/.local/share/overwatch/"
TEAL, WHITE = (95, 215, 232), (230, 246, 250)

# Poster measurements, in texels of paperposter003a (x right, y down).
CENTRE = (183.75, 98.75)
R_DISC, R_RING = 32.0, 41.25            # the disc, and the outer edge of the clear ring
TIP_UP, TIP_LOW = (138.75, 5.5), (93.0, 52.5)      # the two prong points
OUTER = [(220.0, 46.25), (246.25, 60.0), (246.25, 157.5), (145.0, 157.5)]   # tip_up -> ... -> tip_low, clockwise
A_LOW, A_UP = 177.0, 279.0              # where the prongs' inner edges meet the ring (degrees, y down)
BOX = (93.0, 5.5, 246.25, 157.5)        # bounding box of the whole mark


def on_ring(deg):
    return (CENTRE[0] + R_RING * math.cos(math.radians(deg)), CENTRE[1] + R_RING * math.sin(math.radians(deg)))


def unit(scale=1.0, pad=0.0):
    """Shape mapped into a square of side `scale` with `pad` margin; returns a point mapper and a length mapper."""
    w, h = BOX[2] - BOX[0], BOX[3] - BOX[1]
    side = max(w, h)
    k = (scale - 2 * pad) / side
    ox, oy = pad + (side - w) / 2 * k, pad + (side - h) / 2 * k
    return (lambda p: (ox + (p[0] - BOX[0]) * k, oy + (p[1] - BOX[1]) * k)), (lambda v: v * k)


def render(size, colour=(255, 255, 255), ss=4):
    """The emblem as an RGBA image `size` pixels square."""
    n = size * ss
    pt, ln = unit(n)
    mask = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(mask)
    d.polygon([pt(p) for p in [TIP_UP, *OUTER, TIP_LOW, on_ring(A_LOW), on_ring(A_UP)]], fill=255)
    c = pt(CENTRE)
    for r, fill in ((ln(R_RING), 0), (ln(R_DISC), 255)):
        d.ellipse([c[0] - r, c[1] - r, c[0] + r, c[1] + r], fill=fill)
    mask = mask.resize((size, size), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), colour + (0,))
    out.putalpha(mask)
    return out


def svg(path):
    pt, ln = unit(100)
    f = lambda p: "%.2f %.2f" % pt(p)
    r = ln(R_RING)
    c = pt(CENTRE)
    claw = ("M" + f(TIP_UP) + "".join(" L" + f(p) for p in OUTER) + " L" + f(TIP_LOW) + " L" + f(on_ring(A_LOW))
            + " A%.2f %.2f 0 1 0 %s Z" % (r, r, f(on_ring(A_UP))))      # the long way round: under and up the right
    open(path, "w").write(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">\n'
        '  <!-- Combine claw. Generated by scripts/make-emblem.py; edit the measurements there. -->\n'
        f'  <path fill="#fff" d="{claw}"/>\n'
        f'  <circle fill="#fff" cx="{c[0]:.2f}" cy="{c[1]:.2f}" r="{ln(R_DISC):.2f}"/>\n'
        '</svg>\n')


def spaced(draw, xy, text, font, fill, gap):
    x, y = xy
    for ch in text:
        draw.text((x, y), ch, font=font, fill=fill)
        x += draw.textlength(ch, font=font) + gap
    return x - gap


def logo(path):
    """Boot splash mark, same canvas and layout as before so overwatch.script needs no change."""
    w, h = 900, 420
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    mark = render(236, TEAL)
    img.alpha_composite(mark, ((w - mark.width) // 2, 6))
    d = ImageDraw.Draw(img)
    def face(name, size):      # the game fonts may be absent (no anniversary update, no Entropy Zero 2)
        try:
            return ImageFont.truetype(DATA + "fonts/" + name, size)
        except OSError:
            return None
    bold = face("gordin-bold.ttf", 62) or ImageFont.load_default(62)
    script = face("UniversalUnion.ttf", 26)
    gap = 17
    width = sum(d.textlength(ch, font=bold) for ch in "OVERWATCH") + gap * 8
    spaced(d, ((w - width) / 2, 262), "OVERWATCH", bold, WHITE + (255,), gap)
    if script:       # the Combine-script line only makes sense in the Combine alphabet
        line = "civil protection terminal"
        d.text(((w - d.textlength(line, font=script)) / 2, 352), line, font=script, fill=TEAL + (255,))
    img.save(path)


def text_art(path, cols=28):
    """Half-block characters; a terminal cell is about twice as tall as wide, so rows = cols / 2."""
    rows = cols // 2
    ss = 8
    big = render(cols * ss, ss=1).getchannel("A")
    cell = lambda x, y: sum(big.crop((x * ss, y * ss, (x + 1) * ss, (y + 1) * ss)).tobytes()) / (255.0 * ss * ss) > 0.5
    lines = []
    for r in range(rows):
        line = ""
        for c in range(cols):
            top, bot = cell(c, 2 * r), cell(c, 2 * r + 1)
            line += "█" if top and bot else "▀" if top else "▄" if bot else " "
        lines.append("$1" + line.rstrip())
    while lines and lines[-1] == "$1":
        lines.pop()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(lines) + "\n")


def check(path):
    """Overlay on the poster: red = ours only, blue = poster only, white = both. Prints the overlap."""
    src = Image.open(DATA + "textures/posters/hl2_paperposter003a.png").convert("L")
    x0, y0 = int(BOX[0]) - 6, 0
    side = 168
    theirs = src.crop((x0, y0, x0 + side, y0 + side)).point(lambda v: 255 if v < 36 else 0)
    k = 4
    ours = Image.new("L", (side * k, side * k), 0)
    d = ImageDraw.Draw(ours)
    m = lambda p: ((p[0] - x0) * k, (p[1] - y0) * k)
    d.polygon([m(p) for p in [TIP_UP, *OUTER, TIP_LOW, on_ring(A_LOW), on_ring(A_UP)]], fill=255)
    c = m(CENTRE)
    for r, fill in ((R_RING * k, 0), (R_DISC * k, 255)):
        d.ellipse([c[0] - r, c[1] - r, c[0] + r, c[1] + r], fill=fill)
    theirs = theirs.resize(ours.size, Image.NEAREST)
    a, b = ours.point(lambda v: v > 127 and 255), theirs
    both = sum(1 for p, q in zip(a.tobytes(), b.tobytes()) if p and q)
    either = sum(1 for p, q in zip(a.tobytes(), b.tobytes()) if p or q)
    Image.merge("RGB", (a, Image.composite(a, Image.new("L", a.size, 0), b), b)).save(path)
    print(f"  overlap with the poster: {both / max(1, either):.1%}  (overlay: {path})")


if __name__ == "__main__":
    svg(ROOT + "/assets/claw.svg")
    logo(ROOT + "/boot/plymouth/overwatch/logo.png")
    text_art(HOME + "/.config/fastfetch/emblem.txt")
    print("  emblem: assets/claw.svg, boot/plymouth/overwatch/logo.png, ~/.config/fastfetch/emblem.txt")
    if "--check" in sys.argv:
        check(sys.argv[sys.argv.index("--check") + 1] if len(sys.argv) > sys.argv.index("--check") + 1 else "/tmp/claw-check.png")
